/** The items a viewer shows: gated ones out, and no separator left at an edge or doubled. */
export function visibleItems(capEnabled = () => true) {
  const kept = MENU_ITEMS.filter((it) => it.sep || !it.cap || capEnabled(it.cap));
  return kept.filter((it, i) => !it.sep || (i > 0 && i < kept.length - 1 && !kept[i - 1].sep));
}
